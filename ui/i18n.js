export function resolveLanguage(preference = 'System', system = globalThis.navigator?.language || 'en') {
  if (preference === 'Russian' || preference === 'ru') return 'ru';
  if (preference === 'English' || preference === 'en') return 'en';
  return /^ru(?:[-_]|$)/i.test(system) ? 'ru' : 'en';
}

let language = resolveLanguage();
export const locale = () => language;
export function configureLanguage(preference, system) {
  language = resolveLanguage(preference, system);
  if (globalThis.document) document.documentElement.lang = language;
  return language;
}
export function t(key, values = {}) {
  const text = language === 'ru' ? (russian[key] ?? key) : key;
  return text.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name]) : token);
}
export function errorText(error) {
  const text = String(error instanceof Error ? error.message : error).replace(/^Error: /, '');
  if (language !== 'ru') return text;
  if (Object.hasOwn(russian, text)) return t(text);
  for (const key of Object.keys(russian)) {
    if (!key.includes('{error}')) continue;
    const [prefix, suffix] = key.split('{error}');
    if (text.startsWith(prefix) && text.endsWith(suffix)) {
      return t(key, {error: text.slice(prefix.length, suffix ? -suffix.length : undefined)});
    }
  }
  return text;
}

export function translateShell(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-label]')) node.setAttribute('aria-label', t(node.dataset.i18nLabel));
}
